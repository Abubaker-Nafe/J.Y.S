export function getDictionary(locale: Locale): Record<string, string> {
  return locale === "ar" ? { ...en, ...ar } : en;
}

export function translate(locale: Locale, key: string, values?: Record<string, string | number>): string {
  let message = getDictionary(locale)[key] ?? en[key] ?? key;
  if (values) {
    for (const [name, value] of Object.entries(values)) message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}
